fn base_char(c: char) -> char {
    let c = match c {
        'á' | 'à' | 'â' | 'ã' | 'ä' | 'Á' | 'À' | 'Â' | 'Ã' => 'A',
        'é' | 'ê' | 'É' | 'Ê' => 'E',
        'í' | 'Í' => 'I',
        'ó' | 'ô' | 'õ' | 'Ó' | 'Ô' | 'Õ' => 'O',
        'ú' | 'ü' | 'Ú' => 'U',
        'ç' | 'Ç' => 'C',
        c => c,
    };
    c.to_ascii_uppercase()
}

/// Largura do texto em pixels.
pub fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        n * (W + 1) * scale - scale
    }
}

/// Desenha `text` com o canto superior esquerdo em (`x`, `y`).
pub fn draw_text(img: &mut RgbImage, x: i32, y: i32, text: &str, scale: u32, color: [u8; 3]) {
    let (iw, ih) = (img.width() as i32, img.height() as i32);
    let s = scale as i32;
    for (i, c) in text.chars().enumerate() {
        let rows = glyph(base_char(c));
        let gx = x + i as i32 * (W as i32 + 1) * s;
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..W as i32 {
                if bits & (0x10 >> rx) == 0 {
                    continue;
                }
                for dy in 0..s {
                    for dx in 0..s {
                        let px = gx + rx * s + dx;
                        let py = y + ry as i32 * s + dy;
                        if (0..iw).contains(&px) && (0..ih).contains(&py) {
                            img.put_pixel(px as u32, py as u32, Rgb(color));
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn draws_inside_bounds_only() {
        let mut img = RgbImage::new(40, 20);
        draw_text(&mut img, 1, 1, "Olá", 2, [255, 255, 255]);
        draw_text(&mut img, 35, 15, "XYZ", 3, [255, 0, 0]);
        assert!(img.pixels().any(|p| p.0 == [255, 255, 255]));
        assert_eq!(text_width("AB", 2), 22);
    }
}
